/**
 * Get all unique data sources available
 */
export const getDataSources = () => {
  const sources = new Set(waterQualityDataset.map((item) => item.source));
  return Array.from(sources);
};

/**
 * Filter dataset by source
 */
export const filterBySource = (source) => {
  if (!source || source === 'All') return waterQualityDataset;
  return waterQualityDataset.filter((item) => item.source === source);
};

/**
 * Get dataset statistics
 */
export const getDatasetStats = () => {
  const stats = {
    totalPoints: waterQualityDataset.length,
    sources: getDataSources(),
    avgPh: (
      waterQualityDataset.reduce((sum, item) => sum + item.ph, 0) /
      waterQualityDataset.length
    ).toFixed(2),
    avgTds: Math.round(
      waterQualityDataset.reduce((sum, item) => sum + item.tds, 0) /
        waterQualityDataset.length
    ),
    avgTemp: (
      waterQualityDataset.reduce((sum, item) => sum + item.temperature, 0) /
      waterQualityDataset.length
    ).toFixed(2),
  };
  return stats;
};
